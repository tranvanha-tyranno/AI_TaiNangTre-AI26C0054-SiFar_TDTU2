const assert=require('node:assert/strict');
const charts=require('../dashboard/dist/chart-math.js');
const rows=[0,1,2,3,6].map((seconds,i)=>({id:String(i),elapsed_seconds:seconds,status:'ok',outcome:'match',usage:{actual_cost_usd:i===0?0:i/1000,cost_complete:true,total_tokens:i*10,tokens_complete:true}}));
const distribution=charts.distribution(rows,6);
assert.equal(distribution.count,5);
assert.equal(distribution.bins.reduce((sum,b)=>sum+b.ids.length,0),5);
assert.deepEqual(distribution.bins[0].ids,['0']);
assert.deepEqual(distribution.bins[5].ids,['4']);
assert.equal(distribution.median,2);
assert.ok(Math.abs(distribution.p90-4.8)<1e-9);
assert.equal(charts.quantile([],0.5),null);
assert.equal(charts.quantile([0],0.9),0);
const unknown={id:'unknown',elapsed_seconds:2,status:'error',usage:{actual_cost_usd:0,cost_complete:false,total_tokens:0,tokens_complete:false}};
const pending={id:'pending',elapsed_seconds:1,status:'pending',usage:{actual_cost_usd:0,cost_complete:true}};
const scatter=charts.scatter([...rows,unknown,pending]);
assert.equal(scatter.points.length,5);
assert.equal(scatter.excluded,1);
assert.equal(scatter.points[0].y,0); // Real zero is kept; unknown zero is not.
assert.equal(charts.scatter([...rows,unknown],'tokens').excluded,1);
assert.equal(charts.historyValue({finished:true,compared:20,matched:0,api_errors:20,completed:20},'match'),null);
assert.equal(charts.historyValue({finished:true,compared:20,matched:20,api_errors:0,completed:20},'match'),100);
assert.equal(charts.historyValue({finished:false,compared:20,matched:5,api_errors:0,completed:5},'match'),null);
assert.equal(charts.historyValue({finished:true,usage:{actual_cost_usd:0,cost_complete:false}},'cost'),null);
const points=[{index:0,value:1},{index:1,value:null},{index:2,value:3},{index:3,value:4}];
const path=charts.segments(points,p=>p.index,p=>p.value);
assert.equal((path.match(/M/g)||[]).length,2);
assert.equal((path.match(/L/g)||[]).length,1);
assert.equal(charts.distribution([{id:'x',elapsed_seconds:0,status:'ok'}]).bins[0].ids[0],'x');
console.log('Chart math passed: histogram boundaries, percentiles, measured zero vs unknown, pending rows, and gaps in history.');
